"""## 2. Geometric Distance Estimation Theory

To estimate distance using a monocular camera, we leverage the **Pinhole Camera Model** and **Similar Triangles**.

### The Mathematical Formula:

$$D = \frac{F \times H_a}{H_p}$$

Where:
- $D$ = Real-world distance to the object (meters)
- $F$ = Focal length of the camera lens (pixels)
- $H_a$ = Actual, physical height of the object (meters)
- $H_p$ = Apparent height of the object in the camera image (pixels)

### Focal Length Calibration:
If we know an object's real-world height ($H_a$), its distance from the camera during calibration ($D_{calib}$), and its height in pixels ($H_{calib}$), we can calculate the camera's focal length ($F$) using:

$$F = \frac{H_{calib} \times D_{calib}}{H_a}$$
"""

import logging
from typing import Dict, Tuple, Optional

# Configure professional logger for edge devices
logging.basicConfig(level=logging.INFO, format='%(asctime)s - %(levelname)s - %(message)s')
logger = logging.getLogger("RoboticsNavigation")

class DistanceEstimator:
    """
    Computes real-world distance from camera to navigation objects
    using geometric principles (monocular depth estimation).
    """
    def __init__(self, focal_length_px: float):
        if focal_length_px <= 0:
            raise ValueError("Focal length must be a positive non-zero value.")
        self.focal_length = focal_length_px

        # Standard BDD100K class mappings mapped to real-world target heights in meters
        self.known_heights: Dict[str, float] = {
            'traffic cone': 0.70,   # Standard traffic cone
            'cone': 0.70,
            'traffic sign': 0.90,   # Standard signage height
            'stop sign': 0.75,
            'person': 1.70,         # Pedestrian
            'car': 1.50,            # Standard vehicle
            'truck': 2.50,          # Large commercial vehicle
            'rider': 1.65,          # Bicycle / motorcycle rider
            'fence': 1.20,          # Typical road barricade/fence
            'pole': 3.00            # Utility pole / light support
        }

    def estimate(self, label: str, bbox_height_px: float) -> float:
        """
        Calculates distance to object in meters with protection against division by zero and faulty box coordinates.
        """
        if bbox_height_px <= 0:
            logger.warning(f"Invalid bounding box height ({bbox_height_px} px) encountered for label: {label}.")
            return -1.0

        real_height = self.known_heights.get(label.lower(), 0.50) # Defaults safely to 0.5m if target is unknown
        distance = (real_height * self.focal_length) / bbox_height_px
        return round(distance, 2)

    @staticmethod
    def calibrate_focal_length(known_distance_m: float, physical_height_m: float, observed_height_px: float) -> float:
        """
        Back-calculates camera focal length from a calibration target with known parameters.
        """
        if physical_height_m <= 0 or observed_height_px <= 0:
            raise ValueError("Calibration parameters must be strictly greater than zero.")
        focal = (observed_height_px * known_distance_m) / physical_height_m
        logger.info(f"Calibration complete. Computed Focal Length: {focal:.2f} pixels.")
        return focal

"""## 3. Inference, Detection, & Visual Annotation Pipeline

Below is a highly structured class that accepts raw camera frame streams or images, performs object detection, calculates distance dynamically, and overlays professional HUD visual cues.
"""

import numpy as np
import cv2
from ultralytics import YOLO

class RoboticsVisionSystem:
    def __init__(self, model_preset: str = 'yolov8n.pt', focal_length_px: float = 650.0):
        try:
            self.model = YOLO(model_preset)
            logger.info(f"YOLO model '{model_preset}' initialized successfully.")
        except Exception as e:
            logger.error(f"Failed to load the model: {e}")
            raise e

        self.estimator = DistanceEstimator(focal_length_px=focal_length_px)

    def process_frame(self, frame: np.ndarray) -> np.ndarray:
        """
        Processes input video/camera frame, runs inference, evaluates bounding boxes, and overlays distance analytics.
        """
        if frame is None or frame.size == 0:
            logger.error("Encountered an empty or corrupt image frame.")
            return frame

        annotated_frame = frame.copy()
        img_h, img_w = frame.shape[:2]

        try:
            results = self.model(frame, verbose=False)[0]
        except Exception as e:
            logger.error(f"Inference error: {e}")
            return frame

        for box in results.boxes:
            # Fetch tensor values safely
            xyxy = box.xyxy[0].tolist()
            x1, y1, x2, y2 = map(int, xyxy)

            # Clip bounding boxes to image dimensions to avoid out-of-bound errors
            x1, y1 = max(0, x1), max(0, y1)
            x2, y2 = min(img_w - 1, x2), min(img_h - 1, y2)

            bbox_height = y2 - y1
            if bbox_height <= 0:
                continue

            cls_id = int(box.cls[0].item())
            label = results.names[cls_id]
            conf = float(box.conf[0].item())

            # Apply Monocular ranging computations
            distance_m = self.estimator.estimate(label, bbox_height)
            if distance_m < 0:
                continue # Skip processing this box if the distance measurement is invalid

            # Overlay Visual Bounding Boxes with custom depth colors (Closer objects are highlighted in red, farther in green)
            color = (0, 0, 255) if distance_m < 3.0 else (0, 255, 0) # Trigger threshold warning at 3 meters

            cv2.rectangle(annotated_frame, (x1, y1), (x2, y2), color, 2)

            # HUD Overlay String
            hud_text = f"{label.upper()} | {distance_m}m | {conf*100:.1f}%"

            # Display background label box for maximum contrast and legibility
            text_size, _ = cv2.getTextSize(hud_text, cv2.FONT_HERSHEY_SIMPLEX, 0.45, 1)
            text_w, text_h = text_size
            cv2.rectangle(annotated_frame, (x1, max(y1 - text_h - 8, 0)), (x1 + text_w, y1), color, -1)

            # Write text in contrast color (white/black)
            cv2.putText(
                annotated_frame,
                hud_text,
                (x1, max(y1 - 4, 10)),
                cv2.FONT_HERSHEY_SIMPLEX,
                0.45,
                (0, 0, 0) if color == (0, 255, 0) else (255, 255, 255),
                1,
                lineType=cv2.LINE_AA
            )

        return annotated_frame

