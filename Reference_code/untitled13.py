"""## 6. Advanced Robotics: Perspective Transform & Bird's-Eye View (BEV) Map

For a robot to navigate, converting the 2D camera viewpoint into a top-down metric map (**Bird's-Eye View**) is critical. We use a **Homography Matrix** ($H$) to warp our perspective plane onto the ground plane.
"""

def generate_birds_eye_view(image: np.ndarray) -> np.ndarray:
    """
    Warps perspective of input frame to a top-down ground-plane view
    for robot local costmap generation.
    """
    h, w = image.shape[:2]

    # Define coordinates on original perspective image (trapezoid outlining the road)
    src_points = np.float32([
        [w * 0.15, h],
        [w * 0.85, h],
        [w * 0.55, h * 0.5],
        [w * 0.45, h * 0.5]
    ])

    # Define target coordinates on flat top-down grid (rectangle)
    dst_points = np.float32([
        [w * 0.2, h],
        [w * 0.8, h],
        [w * 0.8, 0],
        [w * 0.2, 0]
    ])

    # Compute Homography Matrix
    H = cv2.getPerspectiveTransform(src_points, dst_points)

    # Warp image perspective
    bev_image = cv2.warpPerspective(image, H, (w, h))
    return bev_image

"""## 7. Advanced Robotics: Epipolar Geometry & Disparity Triangulation

When using stereo camera vision systems, depth ($Z$) is derived from the disparity ($d$) between left and right views using focal length ($f$) and baseline distance ($B$):

$$Z = \frac{f \times B}{d}$$

Let's define a mathematical helper to model disparity depth map ranges.
"""

def compute_stereo_depth(disparity_px: float, focal_length_px: float, baseline_m: float = 0.12) -> float:
    """
    Computes depth of obstacles from disparity measurements of stereo camera rigs.
    :param disparity_px: Pixel horizontal displacement between cameras.
    :param focal_length_px: Calibrated camera focal length.
    :param baseline_m: Horizontal distance between left/right optical centers (defaults to 12cm).
    """
    if disparity_px <= 0:
        return float('inf')
    return round((focal_length_px * baseline_m) / disparity_px, 3)

