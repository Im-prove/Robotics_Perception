"""## 9. Advanced Robotics: Sensor Fusion with a 1D Kalman Filter

When we have multiple estimates for distance—one from **Apparent Size** ($z_{size}$) and one from **Ground-Plane Projection** ($z_{ground}$)—we can combine them to get a more robust estimation.

We model this using a **1D Kalman Filter (Weighted Least Squares / Covariance Intersection)** where each estimator has a characteristic measurement uncertainty (variance $\sigma^2$):

$$\mu_{fused} = \frac{\sigma_{ground}^2 \cdot z_{size} + \sigma_{size}^2 \cdot z_{ground}}{\sigma_{size}^2 + 	\sigma_{ground}^2}$$

$$\sigma_{fused}^2 = \frac{\sigma_{size}^2 \cdot \sigma_{ground}^2}{\sigma_{size}^2 + \sigma_{ground}^2}$$
"""

class DistanceSensorFusion:
    """
    Fuses monocular distance estimation techniques (Size-based & Ground-plane projection)
    using a 1D Kalman Filter / covariance weighting system.
    """
    def __init__(self, var_size: float = 0.15, var_ground: float = 0.08):
        # Estimated measurement noise variance of each geometry method
        self.var_size = var_size
        self.var_ground = var_ground

    def fuse(self, d_size: float, d_ground: float) -> Tuple[float, float]:
        """
        Performs optimal 1D Kalman state fusion.
        Returns (fused_distance, fused_variance).
        """
        if d_size <= 0 and d_ground <= 0:
            return 0.0, float('inf')
        if d_size <= 0:
            return round(d_ground, 2), self.var_ground
        if d_ground <= 0:
            return round(d_size, 2), self.var_size

        # Kalman Gain calculation / Weighted variance aggregation
        fused_var = (self.var_size * self.var_ground) / (self.var_size + self.var_ground)
        fused_dist = (d_size * self.var_ground + d_ground * self.var_size) / (self.var_size + self.var_ground)

        return round(fused_dist, 2), round(fused_var, 4)

