def process_official_bdd100k_annotation(label_data: dict, vision_sys: ProductionRoboticsVisionSystem) -> list:
    """
    Parses a standard BDD100K JSON annotation frame and runs physical distance fusion
    on the labeled ground-truth 2D bounding boxes.
    """
    fused_outputs = []
    if not isinstance(label_data, dict):
        print("Warning: Invalid label_data format. Expected dict.")
        return fused_outputs

    frame_name = label_data.get('name', 'unknown')
    print(f"Processing BDD100K Frame: {frame_name}")

    for label_obj in label_data.get('labels', []):
        category = label_obj.get('category')
        box2d = label_obj.get('box2d')
        if not box2d or not category:
            continue

        try:
            x1 = float(box2d.get('x1', 0.0))
            y1 = float(box2d.get('y1', 0.0))
            x2 = float(box2d.get('x2', 0.0))
            y2 = float(box2d.get('y2', 0.0))
        except (ValueError, TypeError) as e:
            print(f"  Warning: Invalid coordinate type in bounding box: {e}")
            continue

        # Safeguard: Validate bounding box height
        bbox_h = y2 - y1
        if bbox_h <= 0:
            print(f"  Warning: Bounding box height for {category} is zero or negative ({bbox_h:.1f}px). Skipping.")
            continue

        # 1. Size-based monocular distance
        d_size = vision_sys.estimator.estimate(category, bbox_h)

        # 2. Physics-based ground plane projection
        d_ground = vision_sys.projector.project_pixel_to_distance(y2)

        # 3. Dynamic Kalman fusion
        fused_d, fused_var = vision_sys.fusion_engine.fuse_estimates(d_size, d_ground)

        fused_outputs.append({
            'category': category,
            'bbox': (x1, y1, x2, y2),
            'fused_distance': fused_d,
            'variance': fused_var
        })
        print(f"  [{category.upper()}] BBox bottom (y2): {y2:.1f}px -> Fused Distance: {fused_d}m (Var: {fused_var})")

    return fused_outputs

